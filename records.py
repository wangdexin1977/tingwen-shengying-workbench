FIELDS = {"event", "job_id", "import_id", "call_id", "part", "status", "provider", "model", "duration_ms", "count", "size_bytes", "audio_duration"}


def append(event, **fields):
    global WRITE_ERROR
    entry = {"time": time.time(), "version": VERSION, "event": event}
    entry.update({k: v for k, v in fields.items() if k in FIELDS and isinstance(v, (str, int, float, bool))})
    # 不接受任意错误文本；模型名可能来自本地配置，拒绝含网址/认证片段的异常值。
    if "model" in entry:
        value = entry["model"]
        entry["model"] = str(value)[:180] if not any(s in str(value).lower() for s in ("http", "bearer", "api_key", "token=")) else "[模型名已隐藏]"
    try:
        with LOCK:
            LOG_FILE.parent.mkdir(exist_ok=True)
            with LOG_FILE.open("a", encoding="utf-8") as output:
                output.write(json.dumps(entry, ensure_ascii=False) + "\n")
        WRITE_ERROR = False
        return True
    except OSError:
        # 记录磁盘问题不妨碍用户的媒体任务；记录接口明确告知不可写。
        WRITE_ERROR = True
        return False


def entries(kind="all", offset=0, limit=100):
    with LOCK:
        rows = []
        if LOG_FILE.exists():
            with LOG_FILE.open(encoding="utf-8") as source:
                for line in source:
                    try:
                        row = json.loads(line)
                        if isinstance(row, dict) and (kind != "models" or row.get("event") == "model_call"):
                            rows.append(row)
                    except (ValueError, TypeError):
                        continue
    rows.reverse()
    return {"entries": rows[offset:offset + limit], "total": len(rows), "offset": offset,
            "next_offset": offset + limit if offset + limit < len(rows) else None}
